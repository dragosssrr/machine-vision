"""dictionary_table.py -- measured properties of some predefined OpenCV marker dictionaries.

For every dictionary: grid size n x n, number of markers, minimum Hamming distance between two *different*
markers (over all four rotations) and the minimum distance of a marker to its *own* rotations, and the number
of bit errors the OpenCV detector can correct (dictionary.maxCorrectionBits).
Output: figures/generated/dict_table.tex  (rows of a tabular) and dict_table.json.   Run: python3 dictionary_table.py
"""
import json
import os
import numpy as np
import cv2

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "figures", "generated")
NAMES = ["DICT_4X4_50", "DICT_5X5_100", "DICT_6X6_250", "DICT_7X7_250", "DICT_APRILTAG_16h5", "DICT_APRILTAG_36h11"]


def all_bits(d):
    """bits[i, r] = flattened n*n bit pattern of marker i rotated by r*90 degrees."""
    n = d.markerSize
    out = np.zeros((len(d.bytesList), 4, n * n), np.uint8)
    for i in range(len(d.bytesList)):
        for r in range(4):
            out[i, r] = cv2.aruco.Dictionary.getBitsFromByteList(d.bytesList[i:i + 1], n, r).ravel()
    return out


rows, js = [], {}
for name in NAMES:
    d = cv2.aruco.getPredefinedDictionary(getattr(cv2.aruco, name))
    B = all_bits(d)
    N, n = B.shape[0], d.markerSize
    base = B[:, 0, :].astype(int)                                  # rotation 0 of every marker
    best = 10 ** 9
    for r in range(4):
        D = (base[:, None, :] != B[None, :, r, :]).sum(axis=2)     # Hamming distance: marker i vs marker j rotated by r
        if r == 0:
            np.fill_diagonal(D, 10 ** 9)                            # a marker is identical to itself (r = 0)
        best = min(best, int(D.min()))
    self_d = min(int((base[i] != B[i, r]).sum()) for i in range(N) for r in (1, 2, 3))
    if "APRILTAG" in name:
        pretty = f"AprilTag {name.split('_')[-1]} ({n}$\\times${n})"
    else:
        pretty = f"ArUco {n}$\\times${n} ({N} ids)"
    rows.append(f"{pretty} & {n*n} & {N} & {best} & {d.maxCorrectionBits}")
    js[name] = dict(n=n, bits=n * n, markers=N, min_hamming_between=best, min_hamming_self_rot=self_d, max_correction_bits=int(d.maxCorrectionBits))
    print(name, js[name])
with open(os.path.join(OUT, "dict_table.tex"), "w") as f:
    f.write("% generated by code/dictionary_table.py -- do not edit; no trailing row end: use \\input{...}\\\\ in the slide\n" + " \\\\\n".join(rows) + "\n")
json.dump(js, open(os.path.join(OUT, "dict_table.json"), "w"), indent=1)
