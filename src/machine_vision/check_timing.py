"""check_timing.py -- add up the minutes announced in the speaker notes, part by part and lecture by lecture.

Every frame carries \\note{... (N min)} or (N s); this script sums them per section file and compares
with the agenda of the opening slide (two lectures of 50 minutes).  Usage (project root):  python3 code/check_timing.py
Lecture 5 begins inside 04_markers.tex with a recap frame; it is counted separately as part "R".
"""
import re, os, sys
# file, part label, title, planned minutes, lecture
AGENDA = [("00_opening", "0", "Opening, running problem", 5, 4), ("01_pose", "1", "Poses and reference frames", 17, 4),
          ("02_camera", "2", "The perspective camera", 16, 4), ("03_calibration", "3", "Lenses, distortion, calibration", 11, 4),
          ("04_markers", "R", "Recap of Lecture 4", 2, 5), ("04_markers", "4", "Fiducial markers and marker pose", 19, 5),
          ("05_relative", "5", "Relative pose, filtering, prediction", 15, 5), ("06_learned", "6", "Learning the pose", 9, 5),
          ("07_project", "7", "Assignment 2, wrap-up", 5, 5)]
RECAP_END = "\\partslide{4}"
bad = False
rows, per_lecture = [], {4: [0.0, 0], 5: [0.0, 0]}
def minutes(txt, name):
    global bad
    mins, n = 0.0, 0
    for note in re.findall(r"\\note\{(.*?)\}\n", txt, re.S):
        m = re.search(r"\(([\d.]+)\s*(min|s)\b[^)]*\)\s*$", note.strip())
        if not m:
            print(f"  !! no timing in a note of {name}: {note[:60]!r}"); bad = True; continue
        v = float(m.group(1)); mins += v if m.group(2) == "min" else v / 60.0; n += 1
    return mins, n
for fname, part, title, planned, lec in AGENDA:
    txt = open(os.path.join("sections", fname + ".tex"), encoding="utf-8").read()
    if fname == "04_markers":
        i = txt.index(RECAP_END)
        txt = txt[:i] if part == "R" else txt[i:]
    mins, n = minutes(txt, fname)
    flag = "" if abs(mins - planned) <= 1.0 else "   <-- differs from the agenda"
    bad |= bool(flag)
    per_lecture[lec][0] += mins; per_lecture[lec][1] += planned
    rows.append(f"{part} & {title} & {lec} & {planned} & {mins:.1f} & {n}")
    print(f"L{lec} part {part:2s} {title:38s} notes {n:2d}  sum {mins:5.1f} min  agenda {planned:2d} min{flag}")
for lec, (m, p) in per_lecture.items():
    flag = "" if m <= 50.0 else "   <-- over 50 min"
    bad |= bool(flag)
    print(f"Lecture {lec}: notes {m:.1f} min, agenda {p} min (slot 50 min){flag}")
tot = sum(v[0] for v in per_lecture.values())
rows.append(f"\\multicolumn{{3}}{{@{{}}l}}{{\\textbf{{total (2 $\\times$ 50 min)}}}} & 100 & {tot:.1f} & {sum(int(r.split(' & ')[-1]) for r in rows)}")
with open(os.path.join("figures", "generated", "timing_table.tex"), "w") as f:
    f.write("% generated by code/check_timing.py -- do not edit; no trailing row end: use \\input{...}\\\\ in the slide\n" + " \\\\\n".join(rows) + "\n")
sys.exit(1 if bad else 0)
